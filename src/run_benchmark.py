"""Run the full SavorLink benchmark: 4 modalities x N seeds, one results table.

Usage:
    python -m src.run_benchmark                      # all modalities, seeds 42,123,456
    python -m src.run_benchmark --modalities taxonomic --seeds 42 --epochs 50

For every modality this trains Strategy III, evaluates it against the
Random / Popularity / kNN / zero-degree-GNN baselines on held-out cold-start
ingredients, saves the trained model under results/models/<modality>/, and
finally writes one combined Markdown table to results/RESULTS.md.
"""
from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path
from typing import Dict, List, Tuple

PROJECT_ROOT = Path(__file__).resolve().parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from src.train import run_pipeline  # noqa: E402

MODALITIES = ["molecular", "semantic", "hybrid", "taxonomic"]
METRICS = [("recall_10", "Recall@10"), ("recall_20", "Recall@20"), ("mrr", "MRR"),
           ("ndcg_20", "NDCG@20"), ("spearman", "Spearman")]
SHARED_BASELINES = ["Random", "Popularity"]


def _fmt(cell: Tuple[float, float]) -> str:
    mean, std = cell
    return f"{mean:.3f} ± {std:.3f}"


def build_results_markdown(tables: Dict[str, Dict[str, Dict[str, Tuple[float, float]]]],
                           seeds: List[int], epochs) -> str:
    """Combine per-modality result tables into one Markdown report."""
    head = "| Model | " + " | ".join(label for _, label in METRICS) + " |"
    rule = "|" + "---|" * (len(METRICS) + 1)
    lines = [
        "# SavorLink benchmark results",
        "",
        f"Generated by `python -m src.run_benchmark` on {time.strftime('%Y-%m-%d %H:%M')}.",
        f"Seeds: {', '.join(map(str, seeds))}. Epochs: {epochs or 'config default'}. "
        "Values are mean ± std across seeds; hub-only mode, CSV recipe-edge ground truth.",
        "",
    ]
    first = next(iter(tables.values()))
    lines += ["## Modality-independent baselines", "", head, rule]
    for name in SHARED_BASELINES:
        if name in first:
            lines.append(f"| {name} | " + " | ".join(_fmt(first[name][k]) for k, _ in METRICS) + " |")
    for modality, table in tables.items():
        lines += ["", f"## {modality.capitalize()}", "", head, rule]
        for name, row in table.items():
            if name in SHARED_BASELINES:
                continue
            lines.append(f"| {name} | " + " | ".join(_fmt(row[k]) for k, _ in METRICS) + " |")
    lines.append("")
    return "\n".join(lines)


def canonical_name(name: str) -> str:
    """Map per-modality labels ('Taxonomic-kNN', 'Strategy III (Taxonomic)') to shared keys."""
    if name.endswith("-kNN"):
        return "kNN"
    if name.startswith("Strategy III"):
        return "Strategy III"
    return name


def build_results_json(tables, seeds: List[int], epochs) -> dict:
    """Structured results for the terminal comparison and the frontend."""
    return {
        "generated": time.strftime("%Y-%m-%d %H:%M"),
        "seeds": seeds,
        "epochs": epochs,
        "metrics": [k for k, _ in METRICS],
        "modalities": {
            modality: {
                canonical_name(model): {metric: list(table[model][metric]) for metric, _ in METRICS}
                for model in table
            }
            for modality, table in tables.items()
        },
    }


def main() -> None:
    parser = argparse.ArgumentParser(description="Run the SavorLink 4-modality benchmark")
    parser.add_argument("--config", default=str(PROJECT_ROOT / "configs" / "default.yaml"))
    parser.add_argument("--modalities", default=",".join(MODALITIES))
    parser.add_argument("--seeds", default="42,123,456")
    parser.add_argument("--epochs", type=int, default=None)
    parser.add_argument("--loss", default="bpr", choices=["bpr", "huber"])
    parser.add_argument("--out", default=str(PROJECT_ROOT / "results"))
    args = parser.parse_args()

    modalities = [m.strip() for m in args.modalities.split(",") if m.strip()]
    unknown = set(modalities) - set(MODALITIES)
    if unknown:
        parser.error(f"unknown modality: {', '.join(sorted(unknown))}")
    seeds = [int(s) for s in args.seeds.split(",") if s.strip()]
    out_dir = Path(args.out)

    tables = {}
    for modality in modalities:
        result = run_pipeline(
            args.config, seeds,
            export_dir=str(out_dir / "models" / modality),
            modality=modality, loss=args.loss, epochs=args.epochs,
        )
        tables[modality] = result["final_table"]

    out_dir.mkdir(parents=True, exist_ok=True)
    report = out_dir / "RESULTS.md"
    report.write_text(build_results_markdown(tables, seeds, args.epochs), encoding="utf-8")
    json_path = out_dir / "results.json"
    json_path.write_text(json.dumps(build_results_json(tables, seeds, args.epochs), indent=2), encoding="utf-8")
    print(f"\nCombined results written to {report} and {json_path}")


if __name__ == "__main__":
    main()
